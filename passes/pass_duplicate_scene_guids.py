#!/usr/bin/env python3
"""
Pass: Duplicate Scene GUIDs and Build Settings Order
---------------------------------------------------
Detects duplicate GUIDs across scene .meta files generated by AssetRipper.
Remaps duplicate GUIDs to deterministic, unique GUIDs and updates EditorBuildSettings.asset
preserving the exact scene build order (0..N).
"""

import os
import re
import uuid
from collections import defaultdict

def _read_guid_from_meta(meta_path):
    if not os.path.exists(meta_path):
        return None
    with open(meta_path, "r", encoding="utf-8", errors="ignore") as f:
        txt = f.read(500)
    m = re.search(r"guid:\s*([a-f0-9]{32})", txt)
    return m.group(1) if m else None

def detect(export_dir, profile=None):
    findings = []
    assets_dir = os.path.join(export_dir, "Assets")
    if not os.path.exists(assets_dir):
        return findings

    guid_to_metas = defaultdict(list)
    for root, _, files in os.walk(assets_dir):
        for f in files:
            if f.endswith(".unity.meta"):
                p = os.path.join(root, f)
                g = _read_guid_from_meta(p)
                if g:
                    guid_to_metas[g].append(p)

    for g, metas in guid_to_metas.items():
        if len(metas) > 1:
            findings.append(f"Duplicate scene GUID '{g}' shared by: {', '.join(os.path.basename(m) for m in metas)}")
    return findings

def apply(export_dir, profile=None, dry_run=False):
    assets_dir = os.path.join(export_dir, "Assets")
    bs_path = os.path.join(export_dir, "ProjectSettings", "EditorBuildSettings.asset")
    changes = 0
    details = []

    if not os.path.exists(assets_dir):
        return {"changes_applied": 0, "details": details}

    guid_to_metas = defaultdict(list)
    for root, _, files in os.walk(assets_dir):
        for f in files:
            if f.endswith(".unity.meta"):
                p = os.path.join(root, f)
                g = _read_guid_from_meta(p)
                if g:
                    guid_to_metas[g].append(p)

    guid_replacements = {}
    for g, metas in guid_to_metas.items():
        if len(metas) > 1:
            sorted_metas = sorted(metas)
            for p in sorted_metas[1:]:
                # Use deterministic replacement based on file path to guarantee reproducibility
                new_guid = uuid.uuid5(uuid.NAMESPACE_URL, p).hex
                details.append(f"Remap duplicate GUID in {os.path.basename(p)} from {g} to {new_guid}")
                changes += 1
                guid_replacements[p] = (g, new_guid)
                if not dry_run:
                    with open(p, "r", encoding="utf-8") as fh:
                        content = fh.read()
                    updated = re.sub(r"guid:\s*[a-f0-9]{32}", f"guid: {new_guid}", content)
                    with open(p, "w", encoding="utf-8") as fh:
                        fh.write(updated)

    if guid_replacements and os.path.exists(bs_path):
        with open(bs_path, "r", encoding="utf-8") as fh:
            bs_text = fh.read()
        bs_changed = False
        for p, (old_guid, new_guid) in guid_replacements.items():
            scene_path = p[:-5]  # strip .meta
            rel_path = os.path.relpath(scene_path, export_dir)
            pattern = rf"(path:\s*{re.escape(rel_path)}\s*\n\s*guid:\s*){old_guid}"
            if re.search(pattern, bs_text):
                bs_text = re.sub(pattern, rf"\g<1>{new_guid}", bs_text)
                bs_changed = True
                details.append(f"Updated EditorBuildSettings.asset entry for {rel_path} to {new_guid}")
        if bs_changed:
            changes += 1
            if not dry_run:
                with open(bs_path, "w", encoding="utf-8") as fh:
                    fh.write(bs_text)

    return {"changes_applied": changes, "details": details}

def verify(export_dir, profile=None):
    findings = detect(export_dir, profile)
    return {
        "passed": len(findings) == 0,
        "remaining_issues": len(findings),
        "details": findings
    }
