#!/usr/bin/env python3
"""
Pass: VR Runtime
------------------
Copies tools/vr/LunaVRRuntime.cs into the project (Assets/Scripts/LunaPort/). It asks the Quest
for 72 Hz, frame-paces the game to it, turns on fixed foveated rendering and logs frames that
miss the budget (LUNA_PERF lines in logcat).

It also writes Assets/Scripts/LunaPort/LunaTheaterFov.cs: the field of view each camera of the
theater scenes has in the scene file. With VR on, a camera that has rendered to the headset reads
back the eye's field of view (about 100 degrees), so the runtime cannot learn the scene's value
by reading it once the headset is running (the main menu after quitting a save, Builds 85-87).
"""

import os
import re
import shutil

TARGET = "Assets/Scripts/LunaPort/LunaVRRuntime.cs"
FOV_TARGET = "Assets/Scripts/LunaPort/LunaTheaterFov.cs"
# Same list as LunaVRRuntime.TheaterScenes.
THEATER_SCENES = ["MainMenu", "CHAR_CREATE", "Gameover", "END_A", "END_B", "END_E",
                  "END_EVID", "END_TOWN", "WhatWillBeAtTheEnd"]


def _scene_cameras(path):
    """(indexed path, field of view) for each camera GameObject in a scene file.
    The path is root/child/... with each name followed by its sibling index, as
    LunaTheater.IndexedPath builds it at runtime: 'PLAYER#3/Canvas#0/CAM#1'."""
    text = open(path, encoding="utf-8", errors="ignore").read()
    docs = re.split(r"\n--- !u!(\d+) &(-?\d+)[^\n]*\n", text)
    names, transform_of, parent, children, roots, fovs = {}, {}, {}, {}, [], []
    for i in range(1, len(docs) - 2, 3):
        cls, fid, body = docs[i], docs[i + 1], docs[i + 2]
        if cls == "1":
            m = re.search(r"m_Name: (.*)", body)
            names[fid] = m.group(1).strip() if m else "?"
        elif cls in ("4", "224"):
            g = re.search(r"m_GameObject: \{fileID: (-?\d+)", body)
            f = re.search(r"m_Father: \{fileID: (-?\d+)", body)
            if not g:
                continue
            transform_of[g.group(1)] = fid
            parent[fid] = f.group(1) if f else "0"
            kids = re.search(r"m_Children:\n((?:\s*- \{fileID: -?\d+\}\n)*)", body)
            children[fid] = re.findall(r"fileID: (-?\d+)", kids.group(1)) if kids else []
        elif cls == "20":
            g = re.search(r"m_GameObject: \{fileID: (-?\d+)", body)
            fov = re.search(r"field of view: ([\d.]+)", body)
            ortho = re.search(r"orthographic: (\d)", body)
            if g and fov and not (ortho and ortho.group(1) == "1"):
                fovs.append((g.group(1), float(fov.group(1))))
        elif cls == "1660057539":   # SceneRoots: the root transforms in hierarchy order
            roots = re.findall(r"fileID: (-?\d+)", body)
    go_of = {t: g for g, t in transform_of.items()}
    if not roots:
        roots = [t for t, p in parent.items() if p == "0"]

    def index_of(t):
        p = parent.get(t, "0")
        siblings = roots if p == "0" else children.get(p, [])
        return siblings.index(t) if t in siblings else -1

    out = []
    for g, fov in fovs:
        t = transform_of.get(g)
        if t is None:
            continue
        parts = []
        while t and t != "0" and t in parent:
            parts.append("%s#%d" % (names.get(go_of.get(t), "?"), index_of(t)))
            t = parent[t]
        out.append(("/".join(reversed(parts)), fov))
    return out


def _fov_table(export_dir):
    lines = []
    for scene in THEATER_SCENES:
        path = os.path.join(export_dir, "Assets", "Scenes", scene + ".unity")
        if not os.path.exists(path):
            continue
        for cam_path, fov in sorted(_scene_cameras(path)):
            lines.append('        { "%s/%s", %sf },' % (scene, cam_path.replace('"', '\\"'), repr(fov)))
    return ("// Generated by passes/pass_vr_runtime.py from the theater scenes' files. Do not edit.\n"
            "using System.Collections.Generic;\n\n"
            "public static class LunaTheaterFov\n{\n"
            "    public static readonly Dictionary<string, float> Authored = new Dictionary<string, float>\n    {\n"
            + "\n".join(lines) + "\n    };\n}\n")

def _source():
    repo_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    return os.path.join(repo_root, "tools", "vr", "LunaVRRuntime.cs")

def _same(a, b):
    if not os.path.exists(b):
        return False
    with open(a, "rb") as f1, open(b, "rb") as f2:
        return f1.read() == f2.read()

def _fov_current(export_dir):
    path = os.path.join(export_dir, FOV_TARGET)
    return open(path, encoding="utf-8").read() if os.path.exists(path) else None


def detect(export_dir, profile=None):
    if not os.path.exists(os.path.join(export_dir, "Assets")):
        return []
    findings = []
    if not _same(_source(), os.path.join(export_dir, TARGET)):
        findings.append(f"{TARGET} missing or out of sync with tools/vr/LunaVRRuntime.cs")
    if _fov_current(export_dir) != _fov_table(export_dir):
        findings.append(f"{FOV_TARGET} missing or out of date")
    return findings

def apply(export_dir, profile=None, dry_run=False):
    if not detect(export_dir, profile):
        return {"changes_applied": 0, "details": []}
    if not dry_run:
        target = os.path.join(export_dir, TARGET)
        os.makedirs(os.path.dirname(target), exist_ok=True)
        shutil.copy2(_source(), target)
        with open(os.path.join(export_dir, FOV_TARGET), "w", encoding="utf-8") as f:
            f.write(_fov_table(export_dir))
    return {"changes_applied": 1, "details": [f"Deploy VR runtime to {TARGET}", f"Write {FOV_TARGET}"]}

def verify(export_dir, profile=None):
    findings = detect(export_dir, profile)
    return {
        "passed": len(findings) == 0,
        "remaining_issues": len(findings),
        "details": findings
    }
