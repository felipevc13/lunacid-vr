#!/usr/bin/env python3
"""Static material audit: which materials render through a shader the port has not rewritten.

Shaders in Assets/Shader are either the port's rewrites from the original compiled formula (the
files in the repo's shaders/ folder) or generic replacements pass_shader_stubs generated by blend
type (AssetRipper cannot export shader code). Materials on a generic replacement are the first
suspects; builtin and package shaders are listed apart. Grouped by shader, most used first.

Usage: python3 tools/tour/material_audit.py <ExportedProject> <material_index.json> <out.md>
"""
import json
import os
import re
import sys
from collections import defaultdict

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def main(project, index_path, out_path):
    with open(index_path) as f:
        mats = json.load(f)["materials"]
    rewritten = set(os.listdir(os.path.join(REPO, "shaders")))
    groups = defaultdict(list)
    for name, m in mats.items():
        if not m["scenes"] and not m["prefabs"]:
            continue
        groups[(m["shader"], m.get("shader_file", ""))].append((name, m))

    def kind(key):
        shader, file = key
        if not file:
            return "builtin/package"
        return "rewritten" if file in rewritten else "generic"

    lines = ["# Static material audit", "",
             "Materials on a **generic** shader render with an approximation, not the original formula.", ""]
    for k in ("generic", "builtin/package", "rewritten"):
        rows = sorted(((s, g) for s, g in groups.items() if kind(s) == k), key=lambda x: -len(x[1]))
        total = sum(len(g) for _, g in rows)
        lines += [f"## {k}: {len(rows)} shaders, {total} materials", "",
                  "| shader | materials | scenes | showcase | examples |", "|---|---|---|---|---|"]
        for s, g in rows:
            scenes = sorted({sc for _, m in g for sc in m["scenes"]})
            show = sum(1 for _, m in g if m["resources"])
            ex = ", ".join(n for n, _ in sorted(g)[:4])
            lines.append(f"| {s[0]} ({s[1] or 'builtin'}) | {len(g)} | {len(scenes)} | {show} | {ex} |")
        lines.append("")
    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    for k in ("generic", "builtin/package", "rewritten"):
        n = sum(len(g) for s, g in groups.items() if kind(s) == k)
        print(f"{k}: {n} materials, {sum(1 for s in groups if kind(s) == k)} shaders")


if __name__ == "__main__":
    main(*sys.argv[1:4])
