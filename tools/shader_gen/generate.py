#!/usr/bin/env python3
"""
Turn a shader decompiled by USCSandbox (tools/shader_gen/uscs.py) into a shader for the VR port.

  python3 tools/shader_gen/generate.py --work ~/lunacid-work [--shader 'Shader Forge/Fairy' ...]
  python3 tools/shader_gen/generate.py --in decompiled.shader --out generated.shader

The decompiled file holds one block of HLSL per compiled variant of the PC game (Unity 2020, D3D11).
This script keeps the formulas as they are and only rebuilds what is around them:

  1. Variants. Shader Forge declares its own LIGHTMAP_OFF/ON, DIRLIGHTMAP_OFF/COMBINED/SEPARATE and
     DYNAMICLIGHTMAP_OFF/ON on top of Unity's, so the game holds variants no renderer ever uses
     (LIGHTMAP_OFF with LIGHTMAP_ON). Those are dropped, the *_OFF keywords are removed, and each
     remaining variant becomes one '#if defined(A) && defined(B)' branch, most keywords first, so the
     variant Unity 6 asks for falls into the closest one the game compiled.
  2. Keywords. Unity's own sets (multi_compile_fwdbase, _fwdadd, _shadowcaster, _fog), as the game was
     built, with skip_variants for the keywords the game never compiled.
  3. Stereo. Single-pass instanced / multiview macros in appdata, v2f, vert and frag. The built-in
     names the code uses (unity_MatrixVP, _WorldSpaceCameraPos, unity_ObjectToWorld...) already turn
     into per-eye values in Unity 6 when stereo is on.
  4. Unity 2020 PC -> Unity 6 Quest: the lightmap read gets DecodeLightmap (the PC's lightmaps needed
     no decoding), and glstate_lightmodel_ambient (half the ambient colour in Unity 2020) becomes
     unity_AmbientSky * 0.5.

The output is made from the user's own copy of the game and must never be committed.
"""

import argparse
import json
import os
import re
import shutil
import sys

DIRECTIVE_RE = re.compile(r"^(\s*)#(if|elif|else|endif)\b\s*(.*)$")
HEADER_RE = re.compile(r"^(?:(.*?)\s*)?//\s*(.*?)\s*//\s*([^:/]+):(\w+)\s*$")   # '#else // KW // PASS:Type'
SIMPLE_HEADER_RE = re.compile(r"^(.*?)\s*//\s*([^:/]+):(\w+)\s*$")               # '#if KW // PASS:Type'
DECL_RE = re.compile(r"^\s*(?:uniform\s+)?[A-Za-z_]\w*\s+([A-Za-z_]\w*)\s*(?:\[[^\]]*\])?\s*;")

# Shader Forge's own keyword sets. Unity enables the non-OFF member (LIGHTMAP_ON, DIRLIGHTMAP_COMBINED,
# DYNAMICLIGHTMAP_ON) when it wants it; nothing ever enables DIRLIGHTMAP_SEPARATE.
SF_FAMILIES = {
    "LIGHTMAP_OFF": {"LIGHTMAP_ON"},
    "DIRLIGHTMAP_OFF": {"DIRLIGHTMAP_COMBINED", "DIRLIGHTMAP_SEPARATE"},
    "DYNAMICLIGHTMAP_OFF": {"DYNAMICLIGHTMAP_ON"},
}
NEVER_ENABLED = {"DIRLIGHTMAP_SEPARATE"}

# Keywords declared by Unity's built-in multi_compile shortcuts (built-in render pipeline).
BUILTIN_SETS = {
    "multi_compile_fwdbase": ["DIRECTIONAL", "LIGHTMAP_ON", "DIRLIGHTMAP_COMBINED", "DYNAMICLIGHTMAP_ON",
                              "SHADOWS_SCREEN", "SHADOWS_SHADOWMASK", "LIGHTMAP_SHADOW_MIXING",
                              "LIGHTPROBE_SH", "VERTEXLIGHT_ON"],
    "multi_compile_fwdadd": ["POINT", "SPOT", "DIRECTIONAL", "POINT_COOKIE", "DIRECTIONAL_COOKIE"],
    "multi_compile_fwdadd_fullshadows": ["POINT", "SPOT", "DIRECTIONAL", "POINT_COOKIE", "DIRECTIONAL_COOKIE",
                                         "SHADOWS_DEPTH", "SHADOWS_SCREEN", "SHADOWS_CUBE", "SHADOWS_SOFT",
                                         "SHADOWS_SHADOWMASK", "LIGHTMAP_SHADOW_MIXING"],
    "multi_compile_shadowcaster": ["SHADOWS_DEPTH", "SHADOWS_CUBE"],
    "multi_compile_fog": ["FOG_LINEAR", "FOG_EXP", "FOG_EXP2"],
}

GENERATED_HEADER = ("// Generated by tools/shader_gen/generate.py from this machine's copy of the game,\n"
                    "// decompiled by USCSandbox. Made locally for the VR port: never commit or share it.\n")


# ------------------------------------------------------------------ parsing

class Block:
    def __init__(self, keywords, stage, lines):
        self.keywords = keywords      # tuple of keywords, or None when the block has no condition
        self.stage = stage            # 'vert', 'frag', or 'any' (no condition: classified by content)
        self.lines = lines


def stage_of(program_type):
    t = program_type.lower()
    if "vertex" in t or t.endswith("vs"):
        return "vert"
    if "pixel" in t or t.endswith("fs"):
        return "frag"
    return "any"


def split_cg(lines):
    """Lines between CGPROGRAM and ENDCG -> (pragma lines, [Block])."""
    pragmas, blocks, cur = [], [], None
    loose = []
    for line in lines:
        m = DIRECTIVE_RE.match(line)
        if m:
            kind, rest = m.group(2), m.group(3)
            if cur is not None:
                blocks.append(cur)
                cur = None
            if kind == "endif":
                continue
            h = HEADER_RE.match(rest) if kind == "else" else SIMPLE_HEADER_RE.match(rest)
            if not h:
                raise ValueError("unrecognised directive: %s" % line.strip())
            if kind == "else":
                kws, ptype = h.group(2), h.group(4)
            else:
                kws, ptype = h.group(1), h.group(3)
            keywords = tuple(k.strip() for k in kws.split("&&") if k.strip())
            cur = Block(keywords, stage_of(ptype), [])
            continue
        if cur is not None:
            cur.lines.append(line)
        elif line.strip().startswith("#pragma"):
            pragmas.append(line.strip())
        else:
            loose.append(line)
    if cur is not None:
        blocks.append(cur)
    if any(l.strip() for l in loose):
        # Code outside any #if: a stage with a single variant. It may hold vert, frag or both.
        text = "\n".join(loose)
        stage = "any"
        if "vert(" in text and "frag(" not in text:
            stage = "vert"
        elif "frag(" in text and "vert(" not in text:
            stage = "frag"
        blocks.insert(0, Block(None, stage, loose))
    return pragmas, blocks


def parse(text):
    """Decompiled shader text -> list of ('text', [lines]) and ('cg', pass header lines, [cg lines])."""
    out, buf = [], []
    lines = text.split("\n")
    i = 0
    while i < len(lines):
        if lines[i].strip() == "CGPROGRAM":
            out.append(("text", buf))
            buf = []
            j = i + 1
            while lines[j].strip() != "ENDCG":
                j += 1
            out.append(("cg", lines[i][:len(lines[i]) - len(lines[i].lstrip())], lines[i + 1:j]))
            i = j + 1
            continue
        buf.append(lines[i])
        i += 1
    out.append(("text", buf))
    return out


# ------------------------------------------------------------------ variants

def normalise(keywords):
    """Raw keyword set of a variant -> runtime keyword set, or None if no renderer can ever use it."""
    ks = set(keywords)
    if ks & NEVER_ENABLED:
        return None
    for off, others in SF_FAMILIES.items():
        if off in ks and ks & others:
            return None
    return tuple(sorted(k for k in ks if k not in SF_FAMILIES))


def closest(table, raw):
    """Block for keyword set raw: the same set, else the largest set it contains (what the #if chain
    of the decompiled file selects: a stage can ignore keywords, e.g. vertex code with fewer
    variants than the fragment code), else the block without a condition."""
    if raw in table:
        return table[raw]
    if raw is not None:
        subs = [k for k in table if k is not None and set(k) <= set(raw)]
        if subs:
            return table[max(subs, key=len)]
    return table.get(None)


def pick_variants(blocks):
    """-> [(runtime keywords, vert block or None, frag block or None)], most keywords first."""
    vert, frag, both = {}, {}, None
    for b in blocks:
        if b.keywords is None and b.stage == "any":
            both = b
            continue
        table = vert if b.stage == "vert" else frag
        table.setdefault(b.keywords, b)       # first block of a set carries its declarations
    if both is not None and not vert and not frag:
        return [((), both, None)]
    sets = [k for k in frag if k is not None] or [k for k in vert if k is not None] or [None]
    chosen, seen = [], set()
    for raw in sets:
        rt = () if raw is None else normalise(raw)
        if rt is None or rt in seen:
            continue
        v = closest(vert, raw)
        f = closest(frag, raw)
        if v is None and both is not None:
            v = both
        if v is None or f is None and both is None:
            raise ValueError("variant %s has no %s block" % (" ".join(raw or ()), "vertex" if v is None else "fragment"))
        seen.add(rt)
        chosen.append((rt, v, f))
    chosen.sort(key=lambda c: -len(c[0]))
    return chosen


def light_mode(header_lines):
    for line in header_lines:
        m = re.search(r'"LIGHTMODE"\s*=\s*"(\w+)"', line, re.I)
        if m:
            return m.group(1).upper()
    return ""


def code_of(block):
    """Code lines of a block without comments and declarations (two variants alike if these match)."""
    if block is None:
        return []
    return [l.strip() for l in block.lines
            if l.strip() and not l.strip().startswith("//") and not DECL_RE.match(l)]


def builtin_sets(mode, seen):
    sets = []
    if mode == "FORWARDBASE":
        sets.append("multi_compile_fwdbase")
    elif mode == "FORWARDADD":
        sets.append("multi_compile_fwdadd_fullshadows" if seen & {"SHADOWS_DEPTH", "SHADOWS_CUBE", "SHADOWS_SCREEN"}
                    else "multi_compile_fwdadd")
    elif mode == "SHADOWCASTER":
        sets.append("multi_compile_shadowcaster")
    if seen & {"FOG_LINEAR", "FOG_EXP", "FOG_EXP2"}:
        sets.append("multi_compile_fog")
    return sets


def drop_idle_keywords(mode, variants):
    """A keyword outside Unity's set for this pass (Shader Forge's LIGHTMAP_ON in a ForwardAdd pass)
    would need its own multi_compile and double the variants. Drop it when no variant's code
    changes with it."""
    seen = set(k for rt, _v, _f in variants for k in rt)
    declared = set(k for s in builtin_sets(mode, seen) for k in BUILTIN_SETS[s])
    by = {rt: (v, f) for rt, v, f in variants}
    changed = True
    while changed:                          # dropping one keyword can make another one idle
        changed = False
        for k in sorted(set(x for rt in by for x in rt) - declared):
            idle = True
            for rt, (v, f) in by.items():
                if k not in rt:
                    continue
                # without k, the #if chain falls to the largest variant contained in rt minus k
                rest = set(rt) - {k}
                subs = [s for s in by if k not in s and set(s) <= rest]
                if not subs:
                    idle = False
                    break
                bv, bf = by[max(subs, key=len)]
                if code_of(v) != code_of(bv) or code_of(f) != code_of(bf):
                    idle = False
                    break
            if idle:
                by = {rt: vf for rt, vf in by.items() if k not in rt}
                changed = True
    out = [(rt, v, f) for rt, (v, f) in by.items()]
    out.sort(key=lambda c: -len(c[0]))
    return out


def keyword_pragmas(mode, variants):
    seen = set(k for rt, _v, _f in variants for k in rt)
    sets = builtin_sets(mode, seen)
    declared = set(k for s in sets for k in BUILTIN_SETS[s])
    lines = ["#pragma " + s for s in sets]
    for k in sorted(seen - declared):
        lines.append("#pragma multi_compile _ " + k)
    skip = sorted(declared - seen)
    if skip:
        lines.append("#pragma skip_variants " + " ".join(skip))
    return lines


# ------------------------------------------------------------------ rewriting a block

def depth0_decls(lines):
    """Names declared at file scope (uniforms, samplers) in a block."""
    names, depth = {}, 0
    for i, line in enumerate(lines):
        if depth == 0:
            m = DECL_RE.match(line)
            if m:
                names[m.group(1)] = i
        depth += line.count("{") - line.count("}")
    return names


def add_stereo(lines):
    out, struct = [], None
    for line in lines:
        s = line.strip()
        m = re.match(r"struct\s+(\w+)", s)
        if m:
            struct = m.group(1)
        if s == "};" and struct in ("appdata", "v2f"):
            ind = line[:len(line) - len(line.lstrip())] + "    "
            out.append(ind + ("UNITY_VERTEX_INPUT_INSTANCE_ID" if struct == "appdata" else "UNITY_VERTEX_OUTPUT_STEREO"))
            struct = None
        out.append(line)
        if s == "v2f o;":
            ind = line[:len(line) - len(line.lstrip())]
            out += [ind + "UNITY_SETUP_INSTANCE_ID(v);",
                    ind + "UNITY_INITIALIZE_OUTPUT(v2f, o);",
                    ind + "UNITY_INITIALIZE_VERTEX_OUTPUT_STEREO(o);"]
        elif s == "fout o;":
            ind = line[:len(line) - len(line.lstrip())]
            out.append(ind + "UNITY_SETUP_STEREO_EYE_INDEX_POST_VERTEX(inp);")
    return out


LIGHTMAP_READ_RE = re.compile(r"^(\s*)(\w+) = UNITY_SAMPLE_TEX2D_SAMPLER\(unity_Lightmap, unity_Lightmap, ([^;]+)\);\s*$")


RSQRT_RE = re.compile(r"rsqrt\(([^()]*)\)")


def unity6_rules(lines):
    out = []
    for line in lines:
        line = line.replace("glstate_lightmodel_ambient", "(unity_AmbientSky * 0.5)")
        # Unity 6 renames it on import in place ("Upgrade NOTE"), so the copy in the project never matched.
        line = line.replace("glstate_matrix_projection", "UNITY_MATRIX_P")
        # normalize() of a zero vector: D3D11 drops the NaN in max(), Vulkan does not (a destroyed part's
        # bone scaled to zero gave grey stumps on the Quest). With the clamp a zero vector stays zero.
        line = RSQRT_RE.sub(lambda m: "rsqrt(max(%s, 1e-12))" % m.group(1), line)
        # Front face: D3D11's SV_IsFrontFace is an integer (non-zero in front); Unity's VFACE is a float,
        # negative on back faces. Read as uint, a back face never flipped the normal (Hair's inside came
        # out dark). The decompiled code always has this form.
        line = line.replace("uint facing: VFACE", "float facing : VFACE").replace("facing.x ? ", "facing.x > 0.0 ? ")
        m = LIGHTMAP_READ_RE.match(line)
        out.append(line)
        if m:
            ind, var = m.group(1), m.group(2)
            out.append("%s%s.xyz = DecodeLightmap(%s);" % (ind, var, var))
    return out


# Built-in variables that USCSandbox does not know as built-in (it comments out the others) but that
# Unity 6's UnityShaderVariables.cginc declares: declaring them again is a compile error.
UNITY_DECLARES = {"unity_OrthoParams", "unity_WorldToCamera", "unity_CameraToWorld",
                  "unity_StereoWorldToCamera", "unity_StereoCameraToWorld",
                  "unity_CameraProjection", "unity_CameraInvProjection"}


def block_lines(block, declared, rules=None, mode="", keywords=()):
    """Block text with stereo, Unity 6 rules and the shader's port rules; drops declarations already
    made in this branch."""
    rules = rules or {}
    lines = list(block.lines)
    names = depth0_decls(lines)
    drop = {i for n, i in names.items() if n in declared or n in UNITY_DECLARES}
    declared.update(names)
    lines = [l for i, l in enumerate(lines) if i not in drop]
    lines = unity6_rules(add_stereo(lines))
    vc = rules.get("vertex_color")
    if vc:
        white = "float4(1.0, 1.0, 1.0, 1.0)"
        repl = white if vc == "white" else "lerp(%s, v.color, %s)" % (white, vc.split(":", 1)[1])
        lines = [re.sub(r"\bv\.color\b", repl, l) for l in lines]
    for r in rules.get("replace_when", []):
        if r.get("pass", mode) == mode and set(r.get("keywords", [])) <= set(keywords):
            lines = [re.sub(r["find"], r["replace"], l) for l in lines]
    if mode in rules.get("frag_wrapper", {}):
        lines = [l.replace("fout frag(v2f inp)", "fout frag_game(v2f inp)") for l in lines]
    return lines


# The PC code reads light probe proxy volumes; Unity declares their variables only where they are
# supported (UNITY_LIGHT_PROBE_PROXY_VOLUME), not on mobile. Declared here they stay zero, so
# 'unity_ProbeVolumeParams.x == 1.0' is false and the code takes the plain path, as Unity's does.
PROBE_VOLUME_DECLS = [
    "#if !UNITY_LIGHT_PROBE_PROXY_VOLUME",
    "float4 unity_ProbeVolumeParams;",
    "float4x4 unity_ProbeVolumeWorldToObject;",
    "float3 unity_ProbeVolumeSizeInv;",
    "float3 unity_ProbeVolumeMin;",
    "UNITY_DECLARE_TEX3D_FLOAT(unity_ProbeVolumeSH);",
    "#endif",
]


def condition(rt):
    return " && ".join("defined(%s)" % k for k in rt) if rt else "1"


def generate_cg(indent, header_lines, cg_lines, rules=None):
    rules = rules or {}
    pragmas, blocks = split_cg(cg_lines)
    mode = light_mode(header_lines)
    variants = drop_idle_keywords(mode, pick_variants(blocks))
    out = [indent + "CGPROGRAM"]
    for p in pragmas:
        if p.startswith(("#pragma vertex", "#pragma fragment", "#pragma target")):
            out.append(indent + p)
    out += [indent + p for p in keyword_pragmas(mode, variants)]
    out.append(indent + '#include "UnityCG.cginc"')
    if any("unity_ProbeVolume" in l for l in cg_lines):
        out += [indent + l for l in PROBE_VOLUME_DECLS]
    for d in rules.get("declare", []):
        out.append(indent + d)
    out.append("")
    if len(variants) == 1 and not variants[0][0]:
        rt, v, f = variants[0]
        declared = set()
        for b in (v, f):
            if b is not None:
                out += block_lines(b, declared, rules, mode, rt)
    else:
        for n, (rt, v, f) in enumerate(variants):
            last = n == len(variants) - 1
            if not last:
                out.append("%s#%s %s" % (indent, "if" if n == 0 else "elif", condition(rt)))
            else:
                out.append("%s#else // %s" % (indent, " ".join(rt) or "no keywords"))
            declared = set()
            for b in (v, f):
                if b is not None:
                    out += block_lines(b, declared, rules, mode, rt)
        out.append(indent + "#endif")
    if mode in rules.get("frag_wrapper", {}):
        out.append("")
        out += [indent + l for l in rules["frag_wrapper"][mode]]
    out.append(indent + "ENDCG")
    return out, len(variants)


def apply_text_rules(lines, rules, first):
    """ShaderLab around the code: extra properties (first part only), SubShader tags, pass state."""
    out = list(lines)
    if first and rules.get("properties"):
        for i, l in enumerate(out):
            if l.strip().startswith("Properties"):
                depth, j = 0, i
                while True:
                    depth += out[j].count("{") - out[j].count("}")
                    if depth == 0 and j > i:
                        break
                    j += 1
                ind = out[i][:len(out[i]) - len(out[i].lstrip())] + "    "
                out[j:j] = [ind + p for p in rules["properties"]]
                break
    tags = rules.get("subshader_tags", {})
    for key, value in tags.items():
        out = [re.sub(r'("%s"\s*=\s*)"[^"]*"' % re.escape(key.upper()), r'\1"%s"' % value, l, flags=re.I)
               for l in out]
        if first and not any(re.search(r'"%s"\s*=' % re.escape(key), l, re.I) for l in out):
            for i, l in enumerate(out):                        # tag not there yet: add it to the SubShader's Tags
                if l.strip().startswith("SubShader"):
                    for k in range(i, len(out)):
                        if out[k].strip().startswith("Tags"):
                            ind = out[k][:len(out[k]) - len(out[k].lstrip())] + "    "
                            out.insert(k + 1, '%s"%s"="%s"' % (ind, key.upper(), value))
                            break
                    break
    mode = light_mode(out)
    state = rules.get("pass_state", {}).get(mode)
    if state:
        start = max((i for i, l in enumerate(out) if l.strip().startswith("Pass {")), default=0)
        ind = out[start][:len(out[start]) - len(out[start].lstrip())] + "    "
        for key, value in state.items():
            found = False
            for i in range(start, len(out)):
                if re.match(r"\s*%s\b" % key, out[i]):
                    out[i] = "%s%s %s" % (ind, key, value)
                    found = True
            if not found:                                      # the pass relied on the default: state it
                out.insert(start + 1, "%s%s %s" % (ind, key, value))
    return out


def generate(text, rules=None):
    """Decompiled shader text -> (generated text, {pass index: variant count})."""
    rules = rules or {}
    parts = parse(text)
    out, counts = [GENERATED_HEADER.rstrip("\n")], {}
    prev_text = []
    for i, part in enumerate(parts):
        if part[0] == "text":
            prev_text = apply_text_rules(part[1], rules, i == 0)
            out += prev_text
        else:
            lines, n = generate_cg(part[1], prev_text, part[2], rules)
            counts[len(counts)] = n
            out += lines
    return "\n".join(out), counts


HERE_DIR = os.path.dirname(os.path.abspath(__file__))
RULES_DIR = os.path.join(HERE_DIR, "rules")


def load_rules(file_name):
    """Port rules for a shader file ('Shader Forge_Object.shader' -> rules/Shader Forge_Object.json)."""
    path = os.path.join(RULES_DIR, os.path.splitext(file_name)[0] + ".json")
    if not os.path.isfile(path):
        return {}
    with open(path, encoding="utf-8") as f:
        return json.load(f)


# ------------------------------------------------------------------ CLI

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--work", help="work folder used by uscs.py")
    ap.add_argument("--shader", action="append", help="shader name (repeatable); default: all decompiled")
    ap.add_argument("--in", dest="inp", help="one decompiled .shader file")
    ap.add_argument("--out", help="output file for --in")
    a = ap.parse_args()
    if a.inp:
        text, counts = generate(open(a.inp, encoding="utf-8").read(), load_rules(os.path.basename(a.inp)))
        open(a.out, "w", encoding="utf-8").write(text)
        print("%s: variants per pass %s" % (a.out, list(counts.values())))
        return
    if not a.work:
        sys.exit("give --work or --in/--out")
    root = os.path.join(os.path.abspath(os.path.expanduser(a.work)), "shader_gen")
    index = json.load(open(os.path.join(root, "decompiled", "index.json"), encoding="utf-8"))["shaders"]
    names = a.shader or sorted(n for n, e in index.items() if e.get("decompiled"))
    os.makedirs(os.path.join(root, "generated"), exist_ok=True)
    failed = []
    for name in names:
        e = index.get(name)
        if not e or not e.get("decompiled"):
            failed.append(name)
            print("NOT DECOMPILED", name)
            continue
        src = os.path.join(root, "decompiled", e["decompiled"])
        rules = load_rules(e["decompiled"])
        if rules.get("use_repo_shader"):
            # ours, not derived from the game (e.g. a pass that draws nothing on the Quest): ship it as is
            repo = os.path.dirname(os.path.dirname(HERE_DIR))
            shutil.copy(os.path.join(repo, rules["use_repo_shader"]), os.path.join(root, "generated", e["decompiled"]))
            print("%-50s repo shader %s" % (name, rules["use_repo_shader"]))
            continue
        try:
            text, counts = generate(open(src, encoding="utf-8").read(), rules)
        except ValueError as ex:
            failed.append(name)
            print("FAILED %s: %s" % (name, ex))
            continue
        open(os.path.join(root, "generated", e["decompiled"]), "w", encoding="utf-8").write(text)
        print("%-50s variants per pass %s" % (name, list(counts.values())))
    if failed:
        sys.exit(1)


if __name__ == "__main__":
    main()
