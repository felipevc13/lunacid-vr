    def test_runner_full_cycle(self):
        # Create minimal synthetic export
        scenes_dir = os.path.join(self.assets_dir, "Scenes")
        os.makedirs(scenes_dir)
        shader_dir = os.path.join(self.assets_dir, "Shader")
        os.makedirs(shader_dir)
        editor_dir = os.path.join(self.assets_dir, "Editor")
        os.makedirs(editor_dir)
        mat_dir = os.path.join(self.assets_dir, "Material")
        os.makedirs(mat_dir)

        with open(os.path.join(shader_dir, "MyStub.shader"), "w") as f:
            f.write('//DummyShaderTextExporter\nShader "Custom/Test" {}')
        with open(os.path.join(mat_dir, "Stain_mat.mat"), "w") as f:
            f.write('_Clip: 0\n')

        profile = {"name": "TestGame", "material_overrides": ["Stain_mat.mat"]}

        # Run detect
        d = run_detect(self.test_dir, profile)
        self.assertIn("pass_shader_stubs", d)

        # Run dry-run apply
        a_dry = run_apply(self.test_dir, profile, dry_run=True)
        self.assertGreater(a_dry["pass_shader_stubs"]["changes_applied"], 0)

        # Run real apply
        a_real = run_apply(self.test_dir, profile, dry_run=False)
        self.assertGreater(a_real["pass_shader_stubs"]["changes_applied"], 0)

        # Run real apply 2nd time (idempotency check)
        a_second = run_apply(self.test_dir, profile, dry_run=False)
        for pname, res in a_second.items():
            self.assertEqual(res.get("changes_applied", 0), 0, f"Pass {pname} was not idempotent!")

        # Run verify
        v = run_verify(self.test_dir, profile)
        self.assertTrue(v["all_passed"])


