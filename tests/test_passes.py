    def test_pass_duplicate_scene_guids(self):
        scenes_dir = os.path.join(self.assets_dir, "Scenes")
        os.makedirs(scenes_dir)
        proj_settings = os.path.join(self.test_dir, "ProjectSettings")
        os.makedirs(proj_settings)

        # Create two scenes sharing the exact same GUID
        meta1 = os.path.join(scenes_dir, "SceneA.unity.meta")
        meta2 = os.path.join(scenes_dir, "SceneB.unity.meta")
        shared_guid = "11111111111111111111111111111111"
        with open(meta1, "w") as f:
            f.write(f"fileFormatVersion: 2\nguid: {shared_guid}\n")
        with open(meta2, "w") as f:
            f.write(f"fileFormatVersion: 2\nguid: {shared_guid}\n")

        bs_path = os.path.join(proj_settings, "EditorBuildSettings.asset")
        with open(bs_path, "w") as f:
            f.write(f"  - enabled: 1\n    path: Assets/Scenes/SceneA.unity\n    guid: {shared_guid}\n"
                    f"  - enabled: 1\n    path: Assets/Scenes/SceneB.unity\n    guid: {shared_guid}\n")

        # 1. Detect
        findings = pass_duplicate_scene_guids.detect(self.test_dir)
        self.assertEqual(len(findings), 1)

        # 2. Dry-run
        res_dry = pass_duplicate_scene_guids.apply(self.test_dir, dry_run=True)
        self.assertGreater(res_dry["changes_applied"], 0)
        with open(meta2, "r") as f:
            self.assertIn(shared_guid, f.read())

        # 3. Apply
        res_apply = pass_duplicate_scene_guids.apply(self.test_dir, dry_run=False)
        self.assertGreater(res_apply["changes_applied"], 0)
        with open(meta2, "r") as f:
            self.assertNotIn(shared_guid, f.read())

        # 4. Idempotency (second run must make 0 changes)
        res_second = pass_duplicate_scene_guids.apply(self.test_dir, dry_run=False)
        self.assertEqual(res_second["changes_applied"], 0)

        # 5. Verify
        v = pass_duplicate_scene_guids.verify(self.test_dir)
        self.assertTrue(v["passed"])
        self.assertEqual(v["remaining_issues"], 0)

