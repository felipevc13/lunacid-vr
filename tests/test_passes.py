    def test_unlit_stub_alpha_cutout(self):
        # Regression: Unlit/MenuPainting with an opaque, non-clipping body drew MenuPaint2's
        # transparent area as a black quad over the whole MainMenu scene on Quest.
        shader_dir = os.path.join(self.assets_dir, "Shader")
        os.makedirs(shader_dir)
        # Unlit/MenuPainting itself has been a protected override (the original formula) since ec0c662: the stub
        # logic is checked on another unlit shader with no override.
        body = pass_shader_stubs._build_shader_body("Unlit/StubPainting", "unlit")
        self.assertIn("clip(tex.a * i.color.a - _Cutoff)", body)
        self.assertIn('_Cutoff ("Alpha cutoff", Range(0,1)) = 0', body)
        self.assertFalse(pass_shader_stubs._needs_regeneration(body))

        # A stale unlit stub generated before cutout support is regenerated in place.
        stale = body.replace("if (_Cutoff > 0.01) {", "if (0) {").replace("clip(", "discard_(")
        stale_file = os.path.join(shader_dir, "Unlit_StubPainting.shader")
        with open(stale_file, "w") as f:
            f.write(stale)
        self.assertTrue(pass_shader_stubs._needs_regeneration(stale))
        pass_shader_stubs.apply(self.test_dir, dry_run=False)
        with open(stale_file, "r") as f:
            self.assertEqual(f.read(), body)
        self.assertEqual(pass_shader_stubs.apply(self.test_dir, dry_run=False)["changes_applied"], 0)

