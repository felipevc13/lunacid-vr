    def test_shader_overrides_preserved(self):
        shader_dir = os.path.join(self.assets_dir, "Shader")
        os.makedirs(shader_dir)

        repo_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
        repo_shaders = os.path.join(repo_root, "shaders")

        # Put a dummy stub in Assets/Shader with the same name as a repo override
        target_override = "Shader Forge_Gamma.shader"
        stub_path = os.path.join(shader_dir, target_override)
        with open(stub_path, "w") as f:
            f.write('//DummyShaderTextExporter\nShader "Shader Forge/Gamma" { SubShader {} }')

        # Run apply
        res_apply = pass_shader_stubs.apply(self.test_dir, dry_run=False)
        self.assertGreater(res_apply["changes_applied"], 0)

        # Verify that each repo shader exists in Assets/Shader and has identical hash
        for sname in os.listdir(repo_shaders):
            if sname.endswith(".shader"):
                src_path = os.path.join(repo_shaders, sname)
                dst_path = os.path.join(shader_dir, sname)
                self.assertTrue(os.path.exists(dst_path), f"Override {sname} was not deployed!")

                with open(src_path, "rb") as f1, open(dst_path, "rb") as f2:
                    src_hash = hashlib.sha256(f1.read()).hexdigest()
                    dst_hash = hashlib.sha256(f2.read()).hexdigest()
                self.assertEqual(src_hash, dst_hash, f"Shader override {sname} hash mismatch! Was it overwritten by stub generator?")

